import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const root = path.join(projectRoot, "public/assets/vfx/packs");
const target = path.join(projectRoot, "src/data/vfx/generatedEffects.js");
const allowedLicenses = new Set(["CC0-1.0", "MIT"]);
const supported = new Set([".efkefc"]);

function safePackName(value) {
  if (!/^[a-z0-9][a-z0-9_-]{0,55}$/.test(value)) {
    throw new Error("Pack name must be a safe lowercase ASCII slug.");
  }
  return value;
}

async function listFiles(folder, out = []) {
  for (const entry of await fs.readdir(folder, { withFileTypes: true })) {
    const full = path.join(folder, entry.name);
    if (entry.isSymbolicLink()) throw new Error(`Symlinks are forbidden in VFX packs: ${full}`);
    if (entry.isDirectory()) await listFiles(full, out);
    else if (entry.isFile()) out.push(full);
  }
  return out;
}
function validateMetadata(json, folder) {
  if (!json || !allowedLicenses.has(json.license)) {
    throw new Error(`Missing approved SPDX license (CC0-1.0 or MIT): ${folder}`);
  }
  if (!/^https:\/\//.test(json.sourceUrl || "")) throw new Error(`Missing HTTPS sourceUrl: ${folder}`);
  if (!json.licenseEvidence || typeof json.licenseEvidence !== "string") {
    throw new Error(`Missing licenseEvidence reference: ${folder}`);
  }
}

export async function scanVfxPacks() {
  await fs.mkdir(root, { recursive: true });
  const catalog = [];
  for (const folder of await fs.readdir(root, { withFileTypes: true })) {
    if (!folder.isDirectory()) continue;
    const slug = safePackName(folder.name);
    const absolute = path.join(root, slug);
    const metadata = JSON.parse(await fs.readFile(path.join(absolute, "vfx-pack.json"), "utf8"));
    validateMetadata(metadata, slug);
    const paths = await listFiles(absolute);
    for (const item of paths) {
      if (!supported.has(path.extname(item).toLowerCase())) continue;
      const relative = path.relative(absolute, item).split(path.sep).join("/");
      const id = "IMPORTED_" + slug.toUpperCase().replaceAll("-", "_") + "_" + relative
        .replace(/\.efkefc$/i,"").replace(/[^a-z0-9]+/gi, "_").toUpperCase();
      const segments = relative.split("/").map(encodeURIComponent).join("/");
      const category = metadata.category || "Imported";
      catalog.push({
        id, name: path.basename(item, ".efkefc").replace(/[_-]+/g, " "),
        sourceType: "effekseer", category,
        shape: "impact", duration: 650, scale: 1,
        url: `/assets/vfx/packs/${encodeURIComponent(slug)}/${segments}`,
        license: metadata.license, licenseEvidence: metadata.licenseEvidence,
        sourceUrl: metadata.sourceUrl,
      });
    }
  }
  catalog.sort((a,b)=>a.id.localeCompare(b.id));
  const ids = new Set();
  for (const effect of catalog) {
    if (ids.has(effect.id)) throw new Error(`Duplicate VFX ID: ${effect.id}`);
    ids.add(effect.id);
  }
  await fs.mkdir(path.dirname(target), { recursive: true });
  await fs.writeFile(target,
    "// Auto-generated by npm run vfx:scan. Edit pack metadata instead of this file.\n" +
    "export const IMPORTED_VFX_EFFECTS = Object.freeze(" + JSON.stringify(catalog, null, 2) + ");\n",
    "utf8");
  return catalog;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  scanVfxPacks().then((catalog) => {
    console.log(`Registered ${catalog.length} licensed Effekseer effects.`);
  }).catch((error) => { console.error(error); process.exitCode = 1; });
}
